namespace ReportService.Samples.DatasetGenerator;

/// <summary>The three pilot datasets.</summary>
internal enum DatasetKind
{
    /// <summary>Small invoice-like list without groups.</summary>
    Simple,

    /// <summary>Medium list with contiguous groups and subtotals.</summary>
    Grouped,

    /// <summary>High-volume list for streaming and memory measurements.</summary>
    Volume,
}

/// <summary>Fixed properties of one pilot dataset.</summary>
/// <param name="Kind">Which dataset.</param>
/// <param name="Name">Name used on the command line and in file names.</param>
/// <param name="DatasetId">Value of <c>header.datasetId</c>, also the sample template id.</param>
/// <param name="ReportTitle">Value of <c>header.reportTitle</c>.</param>
/// <param name="DefaultCount">Number of records generated by default.</param>
/// <param name="SampleCount">Number of records in the template's <c>sample.json</c>.</param>
/// <param name="StreamKey">Added to <c>seed * 31</c> to give each dataset its own sequence.</param>
/// <param name="Indented">Whether the file is written indented (small sets) or compact.</param>
/// <param name="GroupIdDigits">Digits of the numeric part of <c>groupId</c>; 0 when the dataset has no groups.</param>
internal sealed record DatasetDefinition(
    DatasetKind Kind,
    string Name,
    string DatasetId,
    string ReportTitle,
    long DefaultCount,
    long SampleCount,
    ulong StreamKey,
    bool Indented,
    int GroupIdDigits)
{
    /// <summary>Whether the records are organised in groups.</summary>
    public bool HasGroups => GroupIdDigits > 0;

    /// <summary>
    /// File name for a given record count: <c>header-items-v1.&lt;name&gt;.&lt;label&gt;.json</c>,
    /// where the label is the count in millions (<c>m</c>), thousands (<c>k</c>) or units.
    /// </summary>
    public string FileName(long count) => $"header-items-v1.{Name}.{CountLabel(count)}.json";

    private static string CountLabel(long count) => count switch
    {
        _ when count % 1_000_000 == 0 => FormattableString.Invariant($"{count / 1_000_000}m"),
        _ when count % 1_000 == 0 => FormattableString.Invariant($"{count / 1_000}k"),
        _ => FormattableString.Invariant($"{count}"),
    };
}

